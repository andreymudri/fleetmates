import assert from 'node:assert/strict'
import { test, before, after } from 'node:test'
import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright-core'
import { build } from 'vite'
import { memoryHarness, token } from '../helpers/memory-harness.mjs'

let browser
const hub = fileURLToPath(new URL('../..', import.meta.url))
before(async () => {
  await build({ configFile: `${hub}/web/vite.config.mjs`, logLevel: 'silent' })
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? '/usr/bin/chromium', headless: true })
})
after(async () => { await browser?.close() })
async function pageFor(t, mode = 'ok', options = {}) {
  const h = await memoryHarness(t, mode, { web: `${hub}/web/dist`, ...options })
  const context = await browser.newContext({ viewport: { width: 1920, height: 1080 } })
  t.after(() => context.close())
  const page = await context.newPage()
  page.setDefaultTimeout(5000)
  await page.goto(`${h.base}/memory#token=${token}`)
  return { h, page }
}
