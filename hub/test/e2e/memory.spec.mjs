test('memory hostile note titles, tags, markdown and question text render without executable markup', async t => {
  const payloads = JSON.parse(await readFile(`${hub}/test/fixtures/ui/memory.json`, 'utf8'))
  const scenario = JSON.parse(await readFile(`${hub}/test/fixtures/vault-mcp/vault22.json`, 'utf8'))
  const worker = scenario.notes.find(note => note.path.endsWith('bullmq-worker.md'))
  worker.body = [`# ${payloads.title}`, ...payloads.body.split('\n')]
  worker.frontmatter.tags = [payloads.tag]
  const { page, h } = await pageFor(t, 'ok', { scenario })
  await page.locator('.graph-node').first().waitFor()
  assert.match(await page.locator('.graph-node').evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')).join(' ')), /U\+202E/)
  await page.goto(`${h.base}/memory/note/${worker.path}`)
  await page.getByRole('heading', { name: /Note/ }).waitFor()
  assert.equal(await page.locator('.memory-note script, .memory-note img, .memory-note a[href^="javascript:"]').count(), 0)
  assert.match(await page.locator('.memory-note').textContent(), /U\+202E/)
  await page.goto(`${h.base}/memory?thread=new`)
  await page.getByRole('textbox', { name: 'Ask your vault' }).fill(payloads.question)
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.locator('.ask-sources .citation').first().waitFor()
  assert.equal(await page.locator('.ask-messages script, .ask-messages img, .ask-messages a[href^="javascript:"]').count(), 0)
  assert.match(await page.locator('.ask-message--user').textContent(), /U\+202E/)
})
