test('memory accessibility has no serious or critical axe violations', async t => {
  const { page, h } = await pageFor(t)
  await page.locator('.graph-node').first().waitFor()
  const source = await readFile(`${hub}/node_modules/axe-core/axe.min.js`, 'utf8')
  const check = async (page, surface) => {
    if (!(await page.evaluate(() => !!window.axe))) await page.evaluate(source)
    const result = await page.evaluate(() => window.axe.run(document))
    assert.deepEqual(result.violations.filter(row => ['serious', 'critical'].includes(row.impact)).map(row => ({ id: row.id, nodes: row.nodes.map(node => node.target) })), [], surface)
  }
  await check(page, 'Graph')
  for (const name of ['Browse by MOC', /Captures/, /Misses/]) { await page.getByRole('tab', { name }).click(); await check(page, String(name)) }
  await page.goto(`${h.base}/memory/note/02-wiki/nestjs/bullmq-worker.md`)
  await page.getByRole('button', { name: 'Ask about this note' }).waitFor()
  await check(page, 'Note preview')
  for (const fixture of ['answer-cited', 'answer-miss', 'general-knowledge']) {
    const answer = await pageFor(t, 'ok', { fixture, delay: '0' })
    await answer.page.getByRole('textbox', { name: 'Ask your vault' }).fill('Question for accessibility')
    await answer.page.getByRole('button', { name: 'Send', exact: true }).click()
    await answer.page.locator('.ask-answer').waitFor()
    await check(answer.page, fixture)
    await answer.page.getByRole('button', { name: 'History', exact: true }).click()
    await check(answer.page, `${fixture} History`)
  }
  const down = await pageFor(t, 'exit1')
  await down.page.getByText('The charts are out of reach').waitFor()
  await check(down.page, 'Degraded card')
  await page.goto(`${h.base}/memory`)
  await page.locator('.graph-node').first().waitFor()
  await page.keyboard.press('Alt+k')
  await page.locator('.palette-input').fill('?retry')
  await page.locator('.palette-row--askVault').waitFor()
  await check(page, 'Question palette')
})
